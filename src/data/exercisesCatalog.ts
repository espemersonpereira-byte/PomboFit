export function getExerciseById(id: string): ExerciseItem | undefined {
  const found = EXERCISES_CATALOG.find((ex) => ex.id === id);
  if (found) return found;
  try {
    if (typeof window !== 'undefined') {
      const raw = localStorage.getItem('pombofit_custom_exercises');
      if (raw) {
        const customs: ExerciseItem[] = JSON.parse(raw);
        const match = customs.find((ex) => ex.id === id);
        if (match) return match;
      }
    }
  } catch {
    // ignore
  }
  return undefined;
}

export function findAlternativeExercises(
  targetExercise: ExerciseItem,
  availableEquipment?: EquipmentCategory[],
  limitations?: string
): ExerciseItem[] {
  const limText = (limitations || '').toLowerCase();
  return EXERCISES_CATALOG.filter((candidate) => {
    if (candidate.id === targetExercise.id) return false;
    if (candidate.muscleGroup !== targetExercise.muscleGroup) return false;
    if (
      availableEquipment &&
      availableEquipment.length > 0 &&
      !availableEquipment.includes(candidate.equipment) &&
      candidate.equipment !== 'Peso corporal'
    ) {
      return false;
    }
    if (limText.includes('ombro') && candidate.jointStressTags.includes('ombro')) return false;
    if (limText.includes('joelho') && candidate.jointStressTags.includes('joelho')) return false;
    if (limText.includes('lombar') && candidate.jointStressTags.includes('lombar')) return false;
    return true;
  }).sort((a, b) => {
    const aSameMove = a.movementType === targetExercise.movementType ? 0 : 1;
    const bSameMove = b.movementType === targetExercise.movementType ? 0 : 1;
    return aSameMove - bSameMove;
  });
}
